/**
 * Lecture et rendu de `config/locales.toml` (ADR 0040) : source unique des langues de
 * l'application, partagee par le web et le Go.
 *
 * Module sans effet de bord : il lit le TOML et PRODUIT le texte des deux fichiers generes,
 * rien de plus. Les ecrivains (`build_i18n_manifests.mjs`) et le controle de fraicheur
 * (`tools/check-generated-types-fresh.mjs`) l'appellent tous deux : le texte attendu d'un
 * fichier genere n'existe qu'ici.
 */
import { readFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import TOML from '@iarna/toml'

const __dirname = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = resolve(__dirname, '..', '..', '..')

export const LOCALES_TOML_PATH = join(REPO_ROOT, 'config', 'locales.toml')
export const LOCALES_TS_PATH = join(REPO_ROOT, 'apps', 'web', 'src', 'lib', 'i18n', 'generated', 'locales.ts')
export const LOCALES_GO_PATH = join(REPO_ROOT, 'apps', 'go-api', 'internal', 'i18n', 'locales_gen.go')

const CODE_PATTERN = /^[a-z]{2,3}$/
const TAG_PATTERN = /^[A-Za-z]{2,3}(-[A-Za-z0-9]{2,8})*$/

/**
 * Lit et valide le fichier. Retourne `{ default, fallback, locales: [{ code, intl, halo, required }] }`.
 * Toute incoherence leve une erreur nommant l'entree fautive : une liste de langues invalide ne
 * doit jamais produire de module genere.
 */
export function loadLocalesConfig(path = LOCALES_TOML_PATH) {
  const parsed = TOML.parse(readFileSync(path, 'utf8'))
  const entries = parsed.locale
  if (!Array.isArray(entries) || entries.length === 0) {
    throw new Error('locales.toml: au moins une entree [[locale]] est requise')
  }

  const locales = entries.map((e, i) => normalizeEntry(e, i))
  const codes = locales.map((l) => l.code)
  const dup = codes.find((c, i) => codes.indexOf(c) !== i)
  if (dup) throw new Error(`locales.toml: code de langue en double : "${dup}"`)

  const def = requireCodeField(parsed, 'default', codes)
  const fallback = requireCodeField(parsed, 'fallback', codes)
  for (const [role, code] of [['default', def], ['fallback', fallback]]) {
    if (!locales.find((l) => l.code === code).required) {
      throw new Error(`locales.toml: la langue "${code}" (${role}) doit etre required = true`)
    }
  }
  return { default: def, fallback, locales }
}

function normalizeEntry(e, i) {
  const where = `locales.toml: entree [[locale]] n°${i + 1}`
  if (typeof e.code !== 'string' || !CODE_PATTERN.test(e.code)) {
    throw new Error(`${where}: "code" doit etre une sous-etiquette BCP-47 en minuscules (ex. "fr")`)
  }
  const at = `${where} ("${e.code}")`
  if (typeof e.intl !== 'string' || !TAG_PATTERN.test(e.intl)) {
    throw new Error(`${at}: "intl" doit etre une etiquette BCP-47 (ex. "fr-FR")`)
  }
  if (!Array.isArray(e.halo) || e.halo.length === 0 || !e.halo.every((t) => typeof t === 'string' && TAG_PATTERN.test(t))) {
    throw new Error(`${at}: "halo" doit etre une liste non vide d'etiquettes BCP-47`)
  }
  if (typeof e.required !== 'boolean') {
    throw new Error(`${at}: "required" doit etre un booleen`)
  }
  return { code: e.code, intl: e.intl, halo: [...e.halo], required: e.required }
}

function requireCodeField(parsed, name, codes) {
  const v = parsed[name]
  if (typeof v !== 'string' || !codes.includes(v)) {
    throw new Error(`locales.toml: "${name}" doit designer une langue listee (${codes.join(', ')}), recu ${JSON.stringify(v)}`)
  }
  return v
}

const quote = (s) => `'${s}'`

/** Texte attendu de `apps/web/src/lib/i18n/generated/locales.ts`. */
export function renderLocalesTS(cfg) {
  const codes = cfg.locales.map((l) => quote(l.code)).join(', ')
  const intl = cfg.locales.map((l) => `  ${l.code}: ${quote(l.intl)},`)
  return [
    '// Auto-genere par scripts/build_i18n_manifests.mjs - NE PAS EDITER A LA MAIN.',
    '// Source : config/locales.toml (ADR 0040)',
    '',
    `export const KNOWN_LOCALES = [${codes}] as const`,
    '',
    'export type KnownLocale = (typeof KNOWN_LOCALES)[number]',
    '',
    `export const DEFAULT_LOCALE: KnownLocale = ${quote(cfg.default)}`,
    '',
    `export const FALLBACK_LOCALE: KnownLocale = ${quote(cfg.fallback)}`,
    '',
    'export const INTL_TAG: Record<KnownLocale, string> = {',
    ...intl,
    '}',
    '',
  ].join('\n')
}

/**
 * Texte attendu de `apps/go-api/internal/i18n/locales_gen.go`. Chaque entree de la table tient
 * sur une ligne : gofmt n'aligne rien, le fichier est stable sans passage de gofmt.
 */
export function renderLocalesGo(cfg) {
  const rows = cfg.locales.map((l) => {
    const halo = l.halo.map((t) => JSON.stringify(t)).join(', ')
    return `\t{code: ${JSON.stringify(l.code)}, intl: ${JSON.stringify(l.intl)}, halo: []string{${halo}}, required: ${l.required}},`
  })
  return [
    '// Code generated by apps/web/scripts/build_i18n_manifests.mjs from config/locales.toml (ADR 0040); DO NOT EDIT.',
    '',
    'package i18n',
    '',
    '// Default est la langue servie quand la demande est vide ou inconnue.',
    `const Default Locale = ${JSON.stringify(cfg.default)}`,
    '',
    '// Fallback est la langue de repli des noms de jeu sans traduction.',
    `const Fallback Locale = ${JSON.stringify(cfg.fallback)}`,
    '',
    '// table liste les langues dans leur ordre d\'affichage.',
    'var table = []entry{',
    ...rows,
    '}',
    '',
  ].join('\n')
}
